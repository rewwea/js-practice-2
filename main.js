// ЗАДАНИЕ 1
//
// Запросите у пользователя число, возведите это число
// во 2-ю степень и выведите на экран.
//
// Тут через prompt спрашиваю число у пользователя.
// prompt сам по себе возвращает строку, поэтому через Number
// сразу превращаю введенное значение в число.
//
// Потом через ** 2 возвожу его во вторую степень
// и результат вывожу обычным alert.

let number = Number(prompt('Задание 1. Введите число:'))

let square = number ** 2

alert('Число во второй степени: ' + square)

// ЗАДАНИЕ 2
//
// Запросите у пользователя 2 числа и выведите среднее
// арифметическое этих чисел.
//
// Тут получаю два числа. Чтобы найти среднее арифметическое,
// надо их сложить и разделить на количество чисел, то есть на 2.
//
// Скобки тут важны, чтобы сначала произошло сложение,
// а уже потом деление.

let number1 = Number(prompt('Задание 2. Введите первое число:'))
let number2 = Number(prompt('Введите второе число:'))

let average = (number1 + number2) / 2

alert('Среднее арифметическое: ' + average)

// ЗАДАНИЕ 3
//
// Запросите у пользователя длину стороны квадрата и
// выведите площадь такого квадрата.
//
// Площадь квадрата считается как сторона во второй степени.
// Поэтому спрашиваю длину стороны и потом делаю side ** 2.
//
// Например если сторона 5, то площадь будет 25.

let side = Number(prompt('Задание 3. Введите длину стороны квадрата:'))

let area = side ** 2

alert('Площадь квадрата: ' + area)

// ЗАДАНИЕ 4
//
// Реализуйте конвертор из километров в мили.
// Значение перевода километров в мили укажите в коде
// как константу.
//
// Тут сначала сделал константу KM_TO_MILES.
// const использую потому что коэффициент перевода у меня
// меняться во время работы программы не должен.
//
// 1 километр примерно равен 0.621371 мили.
//
// Потом просто спрашиваю количество километров и умножаю
// их на этот коэффициент.

const KM_TO_MILES = 0.621371

let kilometers = Number(prompt('Задание 4. Введите количество километров:'))

let miles = kilometers * KM_TO_MILES

alert(kilometers + ' км = ' + miles + ' миль')

// ЗАДАНИЕ 5
//
// Реализуйте калькулятор. Пользователь вводит два числа,
// а программа выводит результаты действий + - * / между
// этими числами.
//
// Тут получаю два числа, а потом просто отдельно считаю
// четыре математические операции.
//
// Для каждой операции сделал свою переменную, чтобы потом
// нормально все результаты разом вывести через один alert.
//
// \n в alert означает перенос строки, чтобы все результаты
// не шли одной длинной строкой.

let calcNumber1 = Number(prompt('Задание 5. Введите первое число:'))

let calcNumber2 = Number(prompt('Введите второе число:'))

let sum = calcNumber1 + calcNumber2
let difference = calcNumber1 - calcNumber2
let multiplication = calcNumber1 * calcNumber2
let division = calcNumber1 / calcNumber2

alert(
	'Сложение: ' +
		sum +
		'\nВычитание: ' +
		difference +
		'\nУмножение: ' +
		multiplication +
		'\nДеление: ' +
		division,
)

// ЗАДАНИЕ 6
//
// Пользователь вводит значения a и b для формулы
// a * x + b = 0, а программа считает и выводит значение x.
//
// Тут по сути надо просто выразить x из обычного уравнения.
//
// a * x + b = 0
// a * x = -b
// x = -b / a
//
// Поэтому спрашиваю a и b, а потом считаю x по этой формуле.

let a = Number(prompt('Задание 6. Введите значение a:'))
let b = Number(prompt('Введите значение b:'))

let x = -b / a

alert('Значение x: ' + x)

// ЗАДАНИЕ 7
//
// Запросите у пользователя текущее время (часы и минуты)
// и выведите, сколько часов и минут осталось до следующего дня.
//
// Тут удобнее сначала вообще все перевести в минуты.
//
// В сутках 24 * 60 = 1440 минут.
// Текущее время перевожу в минуты через hours * 60 + minutes.
// Потом из всех минут суток вычитаю уже прошедшее время.
//
// После этого надо обратно получить часы и минуты.
// Math.floor нужен чтобы получить целое количество часов,
// а через % 60 получаю остаток минут.

let hours = Number(prompt('Задание 7. Введите текущее количество часов:'))

let minutes = Number(prompt('Введите текущее количество минут:'))

let minutesLeft = 24 * 60 - (hours * 60 + minutes)

let hoursLeft = Math.floor(minutesLeft / 60)
let remainingMinutes = minutesLeft % 60

alert(
	'До следующего дня осталось: ' +
		hoursLeft +
		' ч. ' +
		remainingMinutes +
		' мин.',
)

// ЗАДАНИЕ 8
//
// Запросите у пользователя трехзначное число и выведите
// вторую цифру этого числа. Для решения задачи используйте
// оператор % (остаток от деления).
//
// Например есть число 123.
//
// Сначала 123 / 10 получаем 12.3.
// Через Math.floor отбрасываю дробную часть и остается 12.
// Потом 12 % 10 дает остаток 2.
//
// Вот эта 2 как раз и является второй цифрой числа.

let threeDigitNumber = Number(prompt('Задание 8. Введите трехзначное число:'))

let secondDigit = Math.floor(threeDigitNumber / 10) % 10

alert('Вторая цифра числа: ' + secondDigit)

// ЗАДАНИЕ 9
//
// Запросите у пользователя пятизначное число и переместите
// последнюю цифру в начало.
// Из числа 12345 должно получиться число 51234.
//
// Тут сначала через % 10 достаю последнюю цифру.
//
// Например:
// 12345 % 10 = 5
//
// Потом делю число на 10 и через Math.floor убираю дробную
// часть. Из 12345 таким образом остается 1234.
//
// Чтобы пятерку поставить в начало пятизначного числа,
// умножаю ее на 10000 и прибавляю оставшиеся 1234.
//
// Получается:
// 5 * 10000 + 1234 = 51234

let fiveDigitNumber = Number(prompt('Задание 9. Введите пятизначное число:'))

let lastDigit = fiveDigitNumber % 10
let remainingNumber = Math.floor(fiveDigitNumber / 10)

let newNumber = lastDigit * 10000 + remainingNumber

alert('Полученное число: ' + newNumber)

// ЗАДАНИЕ 10
//
// Запросите общую сумму продаж за месяц и посчитайте
// зарплату.
//
// Тут зарплата состоит из фиксированных 250 плюс 10 процентов
// от продаж.
//
// BASE_SALARY и SALES_PERCENT сделал через const, потому что
// это постоянные значения и менять их в программе не надо.
//
// 10 процентов в вычислениях это 0.10.
// Поэтому продажи умножаю на 0.10 и прибавляю базовую зарплату.

let sales = Number(prompt('Задание 10. Введите общую сумму продаж за месяц:'))

const BASE_SALARY = 250
const SALES_PERCENT = 0.1

let salary = BASE_SALARY + sales * SALES_PERCENT

alert('Зарплата за месяц: ' + salary)
